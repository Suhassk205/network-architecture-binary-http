"""Record a deterministic complete exchange from the real TCP implementations."""
import argparse
import io
import os
from pathlib import Path
import socket
import struct
import sys
import tempfile
import threading

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from bhttp.client import fetch
from bhttp.protocol import hexdump
from bhttp.server import Server

ROOT = Path(__file__).resolve().parents[1]
NAMES = ('host', 'user-agent', 'accept', 'content-type', 'content-length', 'server',
         'cache-control', 'last-modified', 'etag', 'x-request-id')


def dump(raw):
    out = io.StringIO()
    hexdump(raw, 'FRAME', out)
    return out.getvalue()


def annotate(raw, direction, index):
    length, kind, flags, rid = struct.unpack('!IBBH', raw[:8])
    lines = [f'### {direction} frame {index}: { {1:"REQUEST", 2:"RESPONSE", 3:"DATA"}[kind] }', '',
             'Offsets below are zero-based within this frame, including its 8-byte header.', '',
             '```text', dump(raw).rstrip(), '```', '',
             '| Offset | Bytes | Interpretation |', '| --- | --- | --- |',
             f'| 0..3 | `{raw[:4].hex(" ")}` | Payload length = {length} bytes |',
             f'| 4 | `{kind:02x}` | Type = {kind} |',
             f'| 5 | `{flags:02x}` | END = {bool(flags & 1)} |',
             f'| 6..7 | `{raw[6:8].hex(" ")}` | Request ID = {rid} |']
    pos = 8
    if kind == 3:
        lines.append(f'| 8..{len(raw)-1} | `{raw[8:].hex(" ")}` | Exact body: `{raw[8:]!r}` |')
        return '\n'.join(lines)
    if kind == 1:
        size = int.from_bytes(raw[9:11], 'big')
        lines.extend(['| 8 | `01` | Method GET |',
                      f'| 9..10 | `{raw[9:11].hex(" ")}` | Path length = {size} |',
                      f'| 11..{10+size} | `{raw[11:11+size].hex(" ")}` | Path `{raw[11:11+size].decode()}` |'])
        pos = 11 + size
    else:
        lines.append(f'| 8..9 | `{raw[8:10].hex(" ")}` | Status = {int.from_bytes(raw[8:10], "big")} |')
        pos = 10
    count = raw[pos]
    lines.append(f'| {pos} | `{count:02x}` | Header count = {count} |')
    pos += 1
    for _ in range(count):
        start = pos
        token = raw[pos]
        pos += 1
        assert 1 <= token <= 10
        size = int.from_bytes(raw[pos:pos+2], 'big')
        pos += 2
        value = raw[pos:pos+size].decode()
        lines.append(f'| {start} | `{token:02x}` | Indexed name `{NAMES[token-1]}` |')
        lines.append(f'| {start+1}..{start+2} | `{raw[start+1:start+3].hex(" ")}` | UTF-8 value length = {size} |')
        lines.append(f'| {pos}..{pos+size-1} | `{raw[pos:pos+size].hex(" ")}` | Value `{value}` |')
        pos += size
    assert pos == len(raw), 'annotation did not consume every byte'
    return '\n'.join(lines)


def artifacts():
    captured = []
    with tempfile.TemporaryDirectory() as temp:
        fixture = Path(temp) / 'hello.txt'
        fixture.write_bytes((ROOT / 'www/hello.txt').read_bytes())
        os.utime(fixture, ns=(1767225600000000000, 1767225600000000000))
        with Server(('127.0.0.1', 0), temp) as server:
            thread = threading.Thread(target=server.serve_forever, daemon=True)
            thread.start()
            try:
                with socket.create_connection(server.server_address, timeout=3) as sock:
                    out = io.BytesIO()
                    status = fetch(sock, 'localhost', 9000, '/hello.txt', 1, out,
                                   lambda raw, direction: captured.append((direction, raw)))
                    assert status == 200 and out.getvalue() == fixture.read_bytes()
            finally:
                server.shutdown()
                thread.join()
    request = b''.join(raw for direction, raw in captured if direction == 'TX')
    response = b''.join(raw for direction, raw in captured if direction == 'RX')
    session = io.StringIO()
    for direction, raw in captured:
        hexdump(raw, direction, session)
    notes = ['# Annotated complete request and response', '',
             'Generated by `python3 tools/capture.py` from the actual client and server on a loopback TCP socket. '
             'The sample file is `www/hello.txt`. The connection uses an ephemeral listening port, while the request host '
             'header is fixed to `localhost:9000` for reproducibility; the protocol does not require the host header to match '
             'the listening port. The temporary fixture modification time is fixed to 1 January 2026 UTC.', '',
             f'The complete request contains **{len(request)} bytes**; the complete response contains **{len(response)} bytes**. '
             'Raw wire bytes are in `request.bin` and `response.bin`; `session.hex` is the verbose frame capture. '
             'No TCP/IP headers are included. Hex offsets reset for each frame.', '',
             'The response has one metadata frame followed by one final DATA frame. END on the request and final '
             'response DATA marks message completion; the server leaves the TCP connection open. '
             'The client closes it after this exchange. The persistence tests separately issue multiple requests on one socket.', '']
    for index, (direction, raw) in enumerate(captured, 1):
        notes.extend([annotate(raw, direction, index), ''])
    notes.extend(['## Header compression example', '',
                  'The name `content-length` would take 14 literal name bytes, plus its one-byte name length. '
                  'Its fixed ID `05` replaces those name bytes; its value remains length-prefixed. '
                  'All ten assigned names are used across the request and successful response. '
                  'Unknown literal names use ID 00 followed by their name length and bytes, as specified in section 4.', '',
                  '## Independent verification', '',
                  'The annotation walks the captured bytes using an independent `struct` parser and asserts that every '
                  'payload byte is consumed. `python3 tools/capture.py --check` regenerates the exchange and requires exact '
                  'byte equality with all four checked-in artifacts. The protocol tests separately exercise unknown-frame '
                  'skipping before and between response frames, and recovery after malformed requests.', ''])
    return {'request.bin': request, 'response.bin': response,
            'session.hex': session.getvalue().encode(), 'annotated-hexdump.md': '\n'.join(notes).encode()}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true', help='verify committed artifacts without rewriting')
    args = parser.parse_args()
    for name, data in artifacts().items():
        path = ROOT / 'docs' / name
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Capture differs: {name}; run python3 tools/capture.py')
        else:
            path.write_bytes(data)
    print('Capture verified.' if args.check else 'Complete exchange captured and annotated.')


if __name__ == '__main__':
    main()
